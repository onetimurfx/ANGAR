/** Generates supabase/samples/sample_catalog.sql from src/data/sample.ts. Run: npx tsx scripts/gen-sample-seed.ts */
import { writeFileSync } from 'node:fs'
import { banners, brands, categories, outfits, products } from '../src/data/sample'

const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const out: string[] = []
out.push(`-- SAMPLE DATA ONLY. Placeholder products/prices/stock for design review and testing.
-- Every product is flagged is_sample = true: the app marks them NAMUNA and place_order refuses them
-- (until settings.allow_sample_orders is switched on). Real products are added later by the admins.
-- GENERATED by scripts/gen-sample-seed.ts. Do not edit by hand.
`)
categories.filter((c) => c.id !== 'all').forEach((c, i) =>
  out.push(`insert into public.categories (id, name, sort_order) values (${q(c.id)}, ${q(c.name)}, ${i}) on conflict (id) do nothing;`))
brands.forEach((b) =>
  out.push(`insert into public.brands (id, name, type) values (${q(b.id)}, ${q(b.name)}, ${q(b.type)}) on conflict (id) do nothing;`))
for (const p of products) {
  out.push(`insert into public.products (id, name, brand_id, category_id, description, price, old_price, type, is_new, active, popularity, is_sample, created_at)
values (${q(p.id)}, ${q(p.name)}, ${q(p.brandId)}, ${q(p.categoryId)}, ${q(p.description)}, ${p.price}, ${p.oldPrice ?? 'null'}, ${q(p.type)}, ${p.isNew}, ${p.active}, ${p.popularity}, true, ${q(p.createdAt)}) on conflict (id) do nothing;`)
  // spread the sample stock over the variants so that the per-product total equals the sample stock
  const combos = p.sizes.flatMap((s) => p.colors.map((c) => ({ s, c })))
  combos.forEach(({ s, c }, i) => {
    const qty = Math.floor(p.stock / combos.length) + (i < p.stock % combos.length ? 1 : 0)
    out.push(`with v as (insert into public.product_variants (product_id, size, color_name, color_hex, sort_order) values (${q(p.id)}, ${q(s)}, ${q(c.name)}, ${q(c.hex)}, ${i}) on conflict (product_id, size, color_name) do nothing returning id)
insert into public.inventory (variant_id, quantity) select id, ${qty} from v on conflict (variant_id) do nothing;`)
  })
}
outfits.forEach((o, i) => {
  out.push(`insert into public.collections (id, kind, title, note, sort_order) values (${q(o.id)}, 'outfit', ${q(o.title)}, ${q(o.note)}, ${i}) on conflict (id) do nothing;`)
  o.productIds.forEach((pid, j) =>
    out.push(`insert into public.collection_items (collection_id, product_id, sort_order) values (${q(o.id)}, ${q(pid)}, ${j}) on conflict do nothing;`))
})
banners.forEach((b, i) =>
  out.push(`insert into public.promotions (title, subtitle, link, tone, sort_order) values (${q(b.title)}, ${q(b.subtitle)}, ${q(b.to)}, ${q(b.tone)}, ${i});`))
writeFileSync('supabase/samples/sample_catalog.sql', out.join('\n') + '\n')
console.log(`wrote ${products.length} products`)
